#!/usr/bin/env node
// Local development host: runs DSH against this checkout in an isolated DSH_HOME.
//
//   pnpm dev [-- <dsh web args>]   set up (once), watch-build, boot `dsh web` with hot reload
//   pnpm dev:setup                 only prepare .dsh-home (profile, link, generated patch)
//   pnpm dev:reset                 delete .dsh-home (profiles, sessions, sign-in cache)
//   node scripts/dev.mjs env       print the shell line to use the dev home by hand
//
// Everything DSH writes (profiles, storages, logs, the Teamwork cache) stays in
// `.dsh-home/`, so ~/.dsh and its installed plugins are untouched. Patch layers, last
// wins: profile layer < .dsh-home/cordis.patch.yml (generated here) < cordis.local.patch.yml
// (yours, gitignored; e.g. `- id: dsh-teamwork\n  config:\n    apiEndpoint: http://localhost:3000`).
// Set DSH_CLI to a specific @deepseek-ai/dsh `lib/bin.js` to use that host instead of `dsh` on PATH.
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const home = join(repo, '.dsh-home');
const profile = 'web';
const profileDir = join(home, 'profiles', profile);
const localPatch = join(repo, 'cordis.local.patch.yml');
const pkg = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8'));
const windows = process.platform === 'win32';
// The profile is a pnpm workspace root nested inside this repo's workspace (as in tests/host).
const env = { ...process.env, DSH_HOME: home, npm_config_ignore_workspace_root_check: 'true' };

const [command = 'start', ...rest] = process.argv.slice(2);
const dshArgs = rest[0] === '--' ? rest.slice(1) : rest;

function dsh(args, options = {}) {
  const cli = process.env.DSH_CLI;
  return cli
    ? spawnSync(process.execPath, [resolve(cli), ...args], { env, stdio: 'inherit', ...options })
    : spawnSync('dsh', args, { env, stdio: 'inherit', shell: windows, ...options });
}

function dshVersion() {
  const result = dsh(['--version'], { stdio: 'pipe', encoding: 'utf8' });
  if (result.error || result.status !== 0) {
    console.error('dsh not found. Install it (npm i -g @deepseek-ai/dsh) or set DSH_CLI to its lib/bin.js.');
    process.exit(1);
  }
  return result.stdout.trim();
}

function setup() {
  const host = dshVersion();
  const pinned = pkg.devDependencies['@deepseek-ai/dsh-agent'];
  if (host !== pinned) console.warn(`[dev] host dsh ${host} differs from the dev-pinned ${pinned}; the plugin resolves @deepseek-ai/* from this repo's node_modules.`);

  if (!existsSync(join(repo, 'lib', 'index.js'))) run('pnpm', ['build']);
  mkdirSync(home, { recursive: true });

  const manifest = join(profileDir, 'package.json');
  const linked = existsSync(manifest) && JSON.parse(readFileSync(manifest, 'utf8')).dependencies?.[pkg.name] === `link:${repo}`;
  if (!linked) {
    console.log(`[dev] linking ${pkg.name} into ${profileDir}`);
    // Creates the profile from the shipped template and appends the package to its bundles.
    const result = dsh(['plugin', '--profile', profile, 'add', `link:${repo}`], { cwd: home });
    if (result.error) console.error(result.error.message);
    if (result.status !== 0) process.exit(result.status ?? 1);
  }

  writeFileSync(join(home, 'cordis.patch.yml'), [
    '# Generated by scripts/dev.mjs on every run; put overrides in cordis.local.patch.yml.',
    '- id: hmr',
    '  config:',
    '    root:',
    `      - ${JSON.stringify(join(repo, 'lib'))}`,
    '- id: dsh-teamwork',
    '  config:',
    `    cachePath: ${JSON.stringify(join(home, 'teamwork-cache.json'))}`,
    '',
  ].join('\n'));
}

function run(cmd, args) {
  const result = spawnSync(cmd, args, { cwd: repo, stdio: 'inherit', shell: windows });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function start() {
  setup();
  const children = [];
  const launch = (cmd, args, options = {}) => {
    const child = spawn(cmd, args, { cwd: repo, stdio: 'inherit', shell: windows, ...options });
    children.push(child);
    return child;
  };
  launch(join(repo, 'node_modules', '.bin', windows ? 'tsc.cmd' : 'tsc'), ['-w', '--preserveWatchOutput']);
  launch(process.execPath, [join(repo, 'scripts', 'build-web.mjs'), '--watch']);

  const patches = existsSync(localPatch) ? ['--patch', localPatch] : [];
  const args = [profile, ...patches, ...dshArgs];
  const host = process.env.DSH_CLI
    ? launch(process.execPath, [resolve(process.env.DSH_CLI), ...args], { env })
    : launch('dsh', args, { env });

  let stopping = false;
  const stop = async (code) => {
    if (stopping) return;
    stopping = true;
    process.exitCode = code;
    await Promise.all(children.map((child) => child.exitCode !== null || child.signalCode !== null
      ? undefined
      : new Promise((done) => { child.once('exit', done); child.kill('SIGTERM'); })));
    // The watch build inlines source maps; leave the committed bundle as `pnpm build` makes it.
    console.log('[dev] rebuilding lib/web/client.js without source maps');
    spawnSync(process.execPath, [join(repo, 'scripts', 'build-web.mjs')], { cwd: repo, stdio: 'inherit' });
  };
  process.on('SIGINT', () => stop(0));
  process.on('SIGTERM', () => stop(0));
  host.on('exit', (code) => stop(code ?? 0));
}

switch (command) {
  case 'start': start(); break;
  case 'setup': setup(); console.log(`[dev] ready: DSH_HOME=${home}`); break;
  case 'reset': rmSync(home, { recursive: true, force: true }); console.log(`[dev] removed ${home}`); break;
  case 'env': console.log(windows ? `$env:DSH_HOME = "${home}"` : `export DSH_HOME=${JSON.stringify(home)}`); break;
  default: console.error(`unknown command: ${command} (start | setup | reset | env)`); process.exit(1);
}
